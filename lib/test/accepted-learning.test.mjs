import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { registerSource } from '../source-registry.mjs';
import { registerLifecycleRecord, transitionLifecycleRecord, readLifecycleRecord, relocateLifecycleRecord } from '../review-lifecycle.mjs';
import { promoteLearning, retrieveLearnings } from '../accepted-learning.mjs';
const agent = { actor: 'test agent', actorType: 'agent', reason: 'test' };
// Human decisions here exist only in disposable synthetic test workspaces.
const human = { actor: 'Test reviewer', actorType: 'human', humanConfirmed: true, reason: 'Reviewed synthetic fixture' };
function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'mole-learning-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, '4-context'), { recursive: true });
  fs.writeFileSync(path.join(root, 'intent.md'), 'Synthetic intent');
  const evidence = registerSource(root, { path: 'intent.md', source_type: 'file', captured_by: 'test' }).source_id;
  const report = `---\nstatus: active\n---\n# Synthetic travel log\nApproved by somebody (reported claim only).\n\n\`\`\`mole-learning\n${JSON.stringify({ schema_version: 1, change_id: 'change-search', release_id: 'release-09', intent_refs: [evidence], evidence_refs: [evidence] })}\n\`\`\`\n\n## What we learned\nObservation: Search typos need a fallback. [Original](https://example.test/source)\n\n## Unresolved questions\nUnknown retention effect.\n`;
  const file = path.join(root, '4-context/report.md');
  fs.writeFileSync(file, report);
  const sourceId = registerSource(root, { path: '4-context/report.md', source_type: 'file', captured_by: 'test' }).source_id;
  const recordId = registerLifecycleRecord(root, { sourceId, state: 'draft', sourceIds: [evidence], ...agent }).record_id;
  const transition = (action, extra = {}) => transitionLifecycleRecord(root, recordId, { action, ...(action === 'approve' || action === 'reject' || action === 'withdraw' ? human : agent), expectedRevision: readLifecycleRecord(root, recordId).revision, ...extra });
  const approve = () => { transition('submit'); transition('approve'); };
  return { root, file, report, recordId, sourceId, evidence, transition, approve };
}
test('reported approval and active frontmatter do not promote drafts, pending or rejected reports', t => {
  const f = fixture(t);
  assert.throws(() => promoteLearning(f.root, { recordId: f.recordId }), /excluded/);
  f.transition('submit');
  assert.throws(() => promoteLearning(f.root, { recordId: f.recordId }), /excluded/);
  f.transition('reject');
  assert.throws(() => promoteLearning(f.root, { recordId: f.recordId }), /excluded/);
  assert.deepEqual(retrieveLearnings(f.root).learnings, []);
});
test('promotion preserves approved bytes, links and human provenance; repeat reads and promotion are stable', t => {
  const f = fixture(t); f.approve();
  const before = fs.readFileSync(path.join(f.root, 'governance/lifecycle/records.json'), 'utf8');
  const first = promoteLearning(f.root, { recordId: f.recordId });
  assert.equal(first.learning.report, f.report);
  assert.equal(first.learning.provenance.approval.actor, 'Test reviewer');
  assert.equal(first.learning.provenance.approval.revision, 3);
  assert.equal(first.learning.provenance.approval.actor_type, 'human');
  assert.ok(first.learning.provenance.approval.at);
  assert.deepEqual(first.learning.intent_refs, [f.evidence]);
  assert.match(first.learning.lesson, /Original/);
  assert.equal(promoteLearning(f.root, { recordId: f.recordId }).changed, false);
  assert.equal(fs.readFileSync(path.join(f.root, 'governance/lifecycle/records.json'), 'utf8'), before);
  assert.equal(retrieveLearnings(f.root, { query: 'fallback', changeId: 'change-search', releaseId: 'release-09' }).learnings.length, 1);
  assert.equal(retrieveLearnings(f.root, { query: 'absent' }).learnings.length, 0);
  const cli = spawnSync(process.execPath, [new URL('../../cli/mole.mjs', import.meta.url).pathname, 'learning', 'show', first.learning.learning_id], { cwd: f.root, encoding: 'utf8' });
  assert.equal(cli.status, 0, cli.stderr);
  assert.equal(JSON.parse(cli.stdout).learnings.length, 1);
});
test('edits invalidate acceptance; corrected and reapproved report retains identity and immutable history', t => {
  const f = fixture(t); f.approve();
  const first = promoteLearning(f.root, { recordId: f.recordId });
  fs.appendFileSync(f.file, '\nCorrection: retention still unknown.\n');
  assert.equal(retrieveLearnings(f.root).learnings.length, 0);
  assert.throws(() => promoteLearning(f.root, { recordId: f.recordId }), /changed/);
  f.transition('revise'); f.transition('submit');
  assert.equal(retrieveLearnings(f.root).learnings.length, 0);
  f.transition('approve');
  assert.equal(retrieveLearnings(f.root).learnings.length, 0, 'old projection must not survive new approval');
  const corrected = promoteLearning(f.root, { recordId: f.recordId });
  assert.equal(corrected.learning.learning_id, first.learning.learning_id);
  assert.notEqual(corrected.path, first.path);
  const result = retrieveLearnings(f.root, { includeHistory: true });
  assert.equal(result.learnings.length, 1);
  assert.equal(result.history.length, 1);
  assert.equal(result.history[0].current, false);
  assert.equal(JSON.parse(fs.readFileSync(path.join(f.root, first.path))).report, f.report);
});
test('source moves retain learning identity and approval, withdrawal removes current learning', t => {
  const f = fixture(t); f.approve();
  const first = promoteLearning(f.root, { recordId: f.recordId });
  fs.renameSync(f.file, path.join(f.root, '4-context/moved.md'));
  relocateLifecycleRecord(f.root, f.recordId, { path: '4-context/moved.md', ...agent });
  assert.equal(promoteLearning(f.root, { recordId: f.recordId }).changed, false);
  assert.equal(retrieveLearnings(f.root).learnings[0].report_path, '4-context/moved.md');
  f.transition('withdraw');
  assert.equal(retrieveLearnings(f.root).learnings.length, 0);
  assert.equal(retrieveLearnings(f.root, { learningId: first.learning.learning_id, includeHistory: true }).history.length, 1);
});
test('tampered projections and symlinks cannot yield accepted learning', t => {
  const f = fixture(t); f.approve();
  const result = promoteLearning(f.root, { recordId: f.recordId });
  const target = path.join(f.root, result.path);
  const stored = JSON.parse(fs.readFileSync(target)); stored.lesson = 'Agent invention';
  fs.writeFileSync(target, JSON.stringify(stored));
  assert.equal(retrieveLearnings(f.root).learnings.length, 0);
  assert.throws(() => promoteLearning(f.root, { recordId: f.recordId }), /conflict/);
  fs.unlinkSync(target); fs.symlinkSync(f.file, target);
  assert.throws(() => retrieveLearnings(f.root), /symlink/);
});
test('human-approved replacement removes superseded learning and records its identity', t => {
  const f = fixture(t); f.approve();
  const first = promoteLearning(f.root, { recordId: f.recordId });
  fs.writeFileSync(path.join(f.root, '4-context/replacement.md'), f.report.replace('fallback.', 'fallback with a clearer recovery message.'));
  const sourceId = registerSource(f.root, { path: '4-context/replacement.md', source_type: 'file', captured_by: 'test' }).source_id;
  const next = registerLifecycleRecord(f.root, { sourceId, state: 'draft', sourceIds: [f.evidence], ...agent }).record_id;
  transitionLifecycleRecord(f.root, next, { action: 'submit', ...agent });
  transitionLifecycleRecord(f.root, next, { action: 'approve', ...human, expectedRevision: 2, supersedes: [f.recordId] });
  assert.equal(retrieveLearnings(f.root).learnings.length, 0);
  const replacement = promoteLearning(f.root, { recordId: next });
  assert.deepEqual(replacement.learning.provenance.supersedes, [first.learning.learning_id]);
  const result = retrieveLearnings(f.root, { includeHistory: true });
  assert.equal(result.learnings.length, 1);
  assert.equal(result.history.length, 1);
});
