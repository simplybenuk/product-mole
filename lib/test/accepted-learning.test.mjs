test('linking already accepted reports can be promoted again without conflicting with the prior snapshot', t => {
  const f = fixture(t); f.approve();
  const old = promoteLearning(f.root, { recordId: f.recordId });
  fs.writeFileSync(path.join(f.root, '4-context/replacement.md'), f.report.replace('fallback.', 'better fallback.'));
  const sourceId = registerSource(f.root, { path: '4-context/replacement.md', source_type: 'file', captured_by: 'test' }).source_id;
  const next = registerLifecycleRecord(f.root, { sourceId, state: 'draft', sourceIds: [f.evidence], ...agent }).record_id;
  transitionLifecycleRecord(f.root, next, { action: 'submit', ...agent });
  transitionLifecycleRecord(f.root, next, { action: 'approve', ...human, expectedRevision: 2 });
  const before = promoteLearning(f.root, { recordId: next });
  f.transition('supersede', { ...human, replacementId: next });
  assert.equal(retrieveLearnings(f.root).learnings.length, 0);
  const after = promoteLearning(f.root, { recordId: next });
  assert.equal(after.learning.learning_id, before.learning.learning_id);
  assert.notEqual(after.path, before.path);
  assert.deepEqual(after.learning.provenance.supersedes, [old.learning.learning_id]);
  assert.equal(after.learning.provenance.replacements[0].actor, 'Test reviewer');
  assert.equal(retrieveLearnings(f.root).learnings.length, 1);
});
